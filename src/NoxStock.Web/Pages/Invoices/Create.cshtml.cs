using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Rendering;
using NoxStock.BusinessPartners;
using NoxStock.Documents;
using NoxStock.Products;
using NoxStock.Settings;

namespace NoxStock.Web.Pages.Invoices;

public class CreateModel : NoxStockPageModel
{
    private static readonly string[] AcceptedDateFormats = ["yyyy-MM-dd", "dd.MM.yyyy", "d.M.yyyy", "MM/dd/yyyy", "M/d/yyyy", "yyyy/MM/dd"];

    [BindProperty(SupportsGet = true)]
    public DocumentType Type { get; set; } = DocumentType.SaleInvoice;

    [BindProperty(SupportsGet = true)]
    public Guid? Id { get; set; }

    [BindProperty]
    public bool IsDocumentNumberAutoGenerated { get; set; }

    [BindProperty]
    public CreateUpdateDocumentDto Invoice { get; set; } = new();

    public List<SelectListItem> BusinessPartners { get; set; } = new();
    public List<SelectListItem> Products { get; set; } = new();
    public decimal DefaultVatRate { get; private set; } = 20;
    public bool UsesSalesPricing => Type is DocumentType.SaleInvoice or DocumentType.Offer or DocumentType.SaleOrder;
    public bool UsesPurchaseCosting => Type is DocumentType.PurchaseInvoice or DocumentType.PurchaseOrder;
    public bool IsTryOnlySalesDocument => Type is DocumentType.SaleInvoice or DocumentType.Offer or
        DocumentType.SaleOrder or DocumentType.Collection or DocumentType.PosSale;
    public bool IsEditing => Id.HasValue;

    private readonly IBusinessPartnerAppService _businessPartnerAppService;
    private readonly IDocumentAppService _documentAppService;
    private readonly IProductAppService _productAppService;
    private readonly ICompanySettingsAppService _companySettingsAppService;

    public CreateModel(
        IBusinessPartnerAppService businessPartnerAppService,
        IDocumentAppService documentAppService,
        IProductAppService productAppService,
        ICompanySettingsAppService companySettingsAppService)
    {
        _businessPartnerAppService = businessPartnerAppService;
        _documentAppService = documentAppService;
        _productAppService = productAppService;
        _companySettingsAppService = companySettingsAppService;
    }

    public async Task OnGetAsync()
    {
        var settings = await _companySettingsAppService.GetAsync();
        DefaultVatRate = settings.DefaultVatRate;

        if (Id.HasValue)
        {
            var document = await _documentAppService.GetAsync(Id.Value);
            if (document.Status != DocumentStatus.Draft)
            {
                throw new Volo.Abp.UserFriendlyException("Yalnızca taslak faturalar düzenlenebilir.");
            }

            Type = document.Type;
            Invoice = new CreateUpdateDocumentDto
            {
                BusinessPartnerId = document.BusinessPartnerId,
                DocNumber = document.DocNumber,
                Type = document.Type,
                Currency = document.Currency,
                ExchangeRate = document.ExchangeRate,
                Date = document.Date,
                DueDate = document.DueDate,
                Description = document.Description,
                Items = document.Items.Select(item => new CreateUpdateDocumentItemDto
                {
                    ProductId = item.ProductId,
                    Quantity = item.Quantity,
                    UnitPrice = item.UnitPrice,
                    IsUnitPriceOverridden = true,
                    VatRate = item.VatRate,
                    DiscountRate = item.DiscountRate,
                    PurchaseDiscount1 = item.PurchaseDiscount1,
                    PurchaseDiscount2 = item.PurchaseDiscount2,
                    PurchaseDiscount3 = item.PurchaseDiscount3,
                    PurchaseDiscount4 = item.PurchaseDiscount4,
                    SalesDiscount1 = item.SalesDiscount1,
                    SalesDiscount2 = item.SalesDiscount2,
                    SalesDiscount3 = item.SalesDiscount3,
                    SalesDiscount4 = item.SalesDiscount4,
                    Total = item.Total
                }).ToList()
            };

            await LoadLookupsAsync(Type);
            return;
        }

        Invoice = new CreateUpdateDocumentDto
        {
            DocNumber = await _documentAppService.GetSuggestedNumberAsync(Type),
            Date = DateTime.Now,
            DueDate = DateTime.Now.AddDays(30),
            Type = Type,
            Currency = IsTryOnlySalesDocument ? "TRY" : settings.DefaultCurrency,
            Items = new List<CreateUpdateDocumentItemDto>() // Starts empty
        };
        IsDocumentNumberAutoGenerated = true;

        await LoadLookupsAsync(Type);
    }

    public async Task<IActionResult> OnPostAsync()
    {
        NormalizeInvoiceItemNumbers();
        NormalizeInvoiceDates();
        Type = Invoice.Type;
        if (IsTryOnlySalesDocument)
        {
            Invoice.Currency = "TRY";
            ModelState.Remove("Invoice.Currency");
        }
        DefaultVatRate = (await _companySettingsAppService.GetAsync()).DefaultVatRate;

        if (!IsEditing && IsDocumentNumberAutoGenerated)
        {
            Invoice.DocNumber = await _documentAppService.GetSuggestedNumberAsync(Invoice.Type);
            ModelState.Remove("Invoice.DocNumber");
        }
        if (!ModelState.IsValid)
        {
            await LoadLookupsAsync(Invoice.Type);
            return Page();
        }

        if (Invoice.Items == null || Invoice.Items.Count == 0)
        {
            ModelState.AddModelError("", "En az bir ürün eklemelisiniz.");
            await LoadLookupsAsync(Invoice.Type);
            return Page();
        }

        // Fetch missing prices if they are 0
        foreach(var item in Invoice.Items)
        {
            if(item.UnitPrice <= 0)
            {
                var product = await _productAppService.GetAsync(item.ProductId);
                item.UnitPrice = Invoice.Type is DocumentType.SaleInvoice or DocumentType.Offer or DocumentType.SaleOrder
                    ? product.SalePrice
                    : product.PurchaseListPrice > 0m ? product.PurchaseListPrice : product.PurchasePrice;
            }
        }

        try
        {
            if (IsEditing)
            {
                await _documentAppService.UpdateAsync(Id!.Value, Invoice);
            }
            else
            {
                await _documentAppService.CreateAsync(Invoice);
            }
        }
        catch (Volo.Abp.BusinessException ex) when (ex.Code == "NoxStock:DocumentNumberAlreadyExists")
        {
            ModelState.AddModelError(nameof(Invoice.DocNumber), L["DocumentNumberAlreadyExists"]);
            await LoadLookupsAsync(Invoice.Type);
            return Page();
        }

        return RedirectToPage(GetRedirectPage(Invoice.Type));
    }

    private void NormalizeInvoiceDates()
    {
        NormalizeDateInput("Invoice.Date", required: true, value => Invoice.Date = value);
        NormalizeDateInput("Invoice.DueDate", required: false, value => Invoice.DueDate = value);
    }

    private void NormalizeInvoiceItemNumbers()
    {
        if (!Request.HasFormContentType || Invoice.Items is null || Invoice.Items.Count == 0)
        {
            return;
        }

        var itemIndexes = Request.Form["Invoice.Items.Index"].ToArray();
        if (itemIndexes.Length == 0)
        {
            itemIndexes = Enumerable.Range(0, Invoice.Items.Count)
                .Select(index => index.ToString(CultureInfo.InvariantCulture))
                .ToArray();
        }

        for (var itemPosition = 0; itemPosition < Invoice.Items.Count && itemPosition < itemIndexes.Length; itemPosition++)
        {
            var item = Invoice.Items[itemPosition];
            var itemPrefix = $"Invoice.Items[{itemIndexes[itemPosition]}]";

            NormalizeDecimalInput($"{itemPrefix}.Quantity", value => item.Quantity = value);
            NormalizeDecimalInput($"{itemPrefix}.UnitPrice", value => item.UnitPrice = value);
            var submittedOverride = Request.Form[$"{itemPrefix}.IsUnitPriceOverridden"].ToString();
            if (bool.TryParse(submittedOverride, out var isOverridden))
            {
                item.IsUnitPriceOverridden = isOverridden;
            }
            NormalizeDecimalInput($"{itemPrefix}.DiscountRate", value => item.DiscountRate = value);
            NormalizeOptionalDecimalInput($"{itemPrefix}.PurchaseDiscount1", value => item.PurchaseDiscount1 = value);
            NormalizeOptionalDecimalInput($"{itemPrefix}.PurchaseDiscount2", value => item.PurchaseDiscount2 = value);
            NormalizeOptionalDecimalInput($"{itemPrefix}.PurchaseDiscount3", value => item.PurchaseDiscount3 = value);
            NormalizeOptionalDecimalInput($"{itemPrefix}.PurchaseDiscount4", value => item.PurchaseDiscount4 = value);
            NormalizeOptionalDecimalInput($"{itemPrefix}.SalesDiscount1", value => item.SalesDiscount1 = value);
            NormalizeOptionalDecimalInput($"{itemPrefix}.SalesDiscount2", value => item.SalesDiscount2 = value);
            NormalizeOptionalDecimalInput($"{itemPrefix}.SalesDiscount3", value => item.SalesDiscount3 = value);
            NormalizeOptionalDecimalInput($"{itemPrefix}.SalesDiscount4", value => item.SalesDiscount4 = value);
            NormalizeDecimalInput($"{itemPrefix}.VatRate", value => item.VatRate = value);
        }
    }

    private void NormalizeDecimalInput(string key, Action<decimal> assign)
    {
        var rawValue = Request.Form[key].ToString();
        ModelState.Remove(key);

        if (decimal.TryParse(rawValue, NumberStyles.Number, CultureInfo.InvariantCulture, out var value))
        {
            assign(value);
            return;
        }

        ModelState.AddModelError(key, "Lütfen geçerli bir sayısal değer girin.");
    }

    private void NormalizeOptionalDecimalInput(string key, Action<decimal> assign)
    {
        if (Request.Form.ContainsKey(key))
        {
            NormalizeDecimalInput(key, assign);
        }
    }

    private void NormalizeDateInput(string key, bool required, Action<DateTime> assign)
    {
        if (!Request.HasFormContentType)
        {
            return;
        }

        var rawValue = Request.Form[key].ToString();
        ModelState.Remove(key);

        if (string.IsNullOrWhiteSpace(rawValue))
        {
            if (required)
            {
                ModelState.AddModelError(key, "Tarih zorunludur.");
            }

            return;
        }

        if (DateTime.TryParseExact(
                rawValue,
                AcceptedDateFormats,
                CultureInfo.InvariantCulture,
                DateTimeStyles.AllowWhiteSpaces,
                out var parsedDate))
        {
            assign(parsedDate);
            return;
        }

        ModelState.AddModelError(key, "Lütfen geçerli bir tarih girin.");
    }

    private async Task LoadLookupsAsync(DocumentType type)
    {
        var targetType = type is DocumentType.PurchaseInvoice or DocumentType.PurchaseOrder
            ? BusinessPartnerType.Supplier
            : BusinessPartnerType.Customer;
        var bpLookup = await _businessPartnerAppService.GetListAsync(new BusinessPartnerGetListInput
        {
            MaxResultCount = 1000,
            Type = targetType
        });
        BusinessPartners = bpLookup.Items.Select(x => new SelectListItem(x.Name, x.Id.ToString())).ToList();
        BusinessPartners.Insert(0, new SelectListItem("Seçiniz...", string.Empty));

        var productLookup = await _productAppService.GetListAsync(new ProductGetListInput
        {
            MaxResultCount = 1000
        });
        // We might want to pass price info to the UI to update inputs on select. We can do this via data- attributes.
        Products = productLookup.Items.Select(x => new SelectListItem
        {
            Text = $"{x.Name} · {x.Sku}" + (string.IsNullOrWhiteSpace(x.Barcode) ? string.Empty : $" · {x.Barcode}") + $" ({x.Quantity} {x.Unit})",
            Value = x.Id.ToString()
        }).ToList();
        Products.Insert(0, new SelectListItem("Ürün seçiniz...", string.Empty));
    }

    public string GetDocumentTitle()
    {
        if (IsEditing)
        {
            return "Taslak Faturayı Düzenle";
        }

        return Type switch
        {
            DocumentType.SaleInvoice => "Yeni Satış Faturası",
            DocumentType.PurchaseInvoice => "Yeni Alış Faturası",
            DocumentType.Offer => "Yeni Teklif",
            DocumentType.SaleOrder => "Yeni Satış Siparişi",
            DocumentType.PurchaseOrder => "Yeni Alış Siparişi",
            _ => "Yeni Belge"
        };
    }

    public string GetPartnerLabel()
    {
        return Type is DocumentType.PurchaseInvoice or DocumentType.PurchaseOrder ? "Tedarikçi" : "Müşteri";
    }

    public string GetRedirectPage(DocumentType type)
    {
        return type == DocumentType.Offer ? "/Offers/Index" :
            type is DocumentType.SaleOrder or DocumentType.PurchaseOrder ? "/Orders/Index" :
            "/Invoices/Index";
    }

}
